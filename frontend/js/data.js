/* ---------- Расписание (демо) ----------
   Та же формула, что в каталоге: свободные окна через k дней от сегодня.
   API: GET /api/psychologists/:id/slots?from=…&to=… */
const DEMO_TODAY = (() => { const d = new Date(); d.setHours(0, 0, 0, 0); return d; })();
const demoDateAt = (k) => { const d = new Date(DEMO_TODAY); d.setDate(d.getDate() + k); return d; };
const demoMins = (t) => { const [h, m] = t.split(':').map(Number); return h * 60 + m; };
const demoSlotsOn = (p, k) => {
  if (k < p.days || !p.work.includes(demoDateAt(k).getDay())) return [];
  const now = new Date();
  return p.slots.filter((t, i) => (p.id * 7 + k * 3 + i) % 5 !== 0
    && (k > 0 || demoMins(t) > now.getHours() * 60 + now.getMinutes() + 30));
};

