/* ---------- Сборка ---------- */
const tests = results.testResults.map((f) => ({
  file: f.name.split('/tests/')[1],
  seconds: (f.endTime - f.startTime) / 1000,
  cases: f.assertionResults.map((t) => ({ name: [...t.ancestorTitles, t.title].join(' › '), status: t.status })),
}));
const allCases = tests.flatMap((f) => f.cases.map((c) => ({ ...c, file: f.file })));
const order = Object.keys(FILES);
tests.sort((a, b) => order.indexOf(a.file) - order.indexOf(b.file));

const pct = (m) => `${m.pct.toFixed(1).replace('.', ',')} %`;
const mark = (status) => (status === 'passed' ? '✓ пройден' : status === 'failed' ? '✗ не пройден' : status);
const date = new Date(results.startTime).toLocaleString('ru-RU', { timeZone: 'Europe/Minsk', dateStyle: 'long', timeStyle: 'short' });
const totalSeconds = tests.reduce((s, f) => s + f.seconds, 0);

// Покрытие по слоям приложения
const LAYERS = [
  ['routes', 'Маршруты (HTTP)'], ['services', 'Сервисы (бизнес-логика)'], ['repositories', 'Репозитории (SQL, Redis)'],
  ['middleware', 'Промежуточные обработчики'], ['socket', 'Socket.IO'], ['db', 'Подключение к БД'], ['', 'Прочее (app, config, errors)'],
];
const layerOf = (file) => {
  const rel = file.split('/src/')[1] || '';
  const dir = rel.includes('/') ? rel.split('/')[0] : '';
  return LAYERS.some(([d]) => d === dir) ? dir : '';
};
const sum = (files) => ['lines', 'branches', 'functions'].reduce((acc, key) => {
  const covered = files.reduce((s, f) => s + coverage[f][key].covered, 0);
  const total = files.reduce((s, f) => s + coverage[f][key].total, 0);
  acc[key] = { pct: total ? (covered / total) * 100 : 100, covered, total };
  return acc;
}, {});
const files = Object.keys(coverage).filter((k) => k !== 'total');

const lines = [];
const out = (s = '') => lines.push(s);
const failed = results.numFailedTests;

