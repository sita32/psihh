out('## Приложение. Полный список тестов');
tests.forEach((f) => {
  out();
  out(`### \`${f.file}\``);
  out();
  f.cases.forEach((c) => out(`- ${c.status === 'passed' ? '✓' : '✗'} ${c.name}`));
});
out();

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`Отчёт: ${OUT} – ${results.numTotalTests} тестов, не пройдено ${failed}`);
process.exit(failed ? 1 : 0);
