out('## 4. Покрытие кода');
out();
out('Доля кода сервера (`backend/src`, кроме точки входа `server.js`), которая выполнялась во время тестов:');
out();
out('| Слой | Файлов | Строки | Ветвления | Функции |');
out('|---|---|---|---|---|');
LAYERS.forEach(([dir, name]) => {
  const group = files.filter((f) => layerOf(f) === dir);
  if (!group.length) return;
  const s = sum(group);
  out(`| ${name} | ${group.length} | ${pct(s.lines)} | ${pct(s.branches)} | ${pct(s.functions)} |`);
});
const t = coverage.total;
out(`| **Всего** | **${files.length}** | **${pct(t.lines)}** (${t.lines.covered} из ${t.lines.total}) | **${pct(t.branches)}** | **${pct(t.functions)}** |`);
out();
